import { NextResponse } from "next/server";
import { createClient } from "@/lib/supabase/server";
import { generateTextWithFallback } from "@/lib/ai/client";

export interface ResearchSource {
  title: string;
  url: string;
  domain: string;
  snippet: string;
}

export interface DeepResearchSection {
  title: string;
  content: string;
  keyTakeaway?: string;
}

export interface DeepResearchReport {
  query: string;
  summary: string;
  sections: DeepResearchSection[];
  sources: ResearchSource[];
  recommendations: string[];
  followUps: string[];
  markdownReport: string;
}

export async function POST(request: Request) {
  try {
    const supabase = await createClient();
    const {
      data: { user },
    } = await supabase.auth.getUser();

    if (!user) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const body = await request.json();
    const query = (body.query || "").trim();
    const depth = body.depth === "quick" ? "quick" : "deep";
    const projectId = body.projectId;

    if (!query) {
      return NextResponse.json({ error: "Please enter a research query." }, { status: 400 });
    }

    // Optional project context
    let projectContext = "";
    if (projectId) {
      const { data: project } = await supabase
        .from("projects")
        .select("name, description")
        .eq("id", projectId)
        .single();

      if (project) {
        projectContext = `\nContextual Project: "${project.name}" (${project.description || "General Context"})\n`;
      }
    }

    const systemPrompt = `
You are the Deep Research Engine inside Orbitwork (an open-source Perplexity / Vane alternative).
Your objective is to provide high-depth, rigorous research, web-grounded analysis, and structured synthesis.

Analyze the user's research question thoroughly:
- Provide an Executive Summary.
- Divide into 3-4 comprehensive sections with authoritative technical or strategic depth.
- Provide real, credible web sources, documentation references, and industry benchmark URLs with snippets.
- Provide actionable recommendations tailored to modern teams.
- Suggest 3 follow-up research questions.

Return ONLY raw JSON conforming to this exact schema (no markdown wrapper, no extra text):
{
  "summary": "Direct, executive answer synthesizing the research topic in 2-3 paragraphs.",
  "sections": [
    {
      "title": "Section Title",
      "content": "In-depth analysis with structured technical, operational, or strategic findings...",
      "keyTakeaway": "One-line summary of this section"
    }
  ],
  "sources": [
    {
      "title": "Authoritative Reference / Doc / Article",
      "url": "https://...",
      "domain": "example.org",
      "snippet": "Crucial finding or citation from this source..."
    }
  ],
  "recommendations": [
    "Concrete actionable recommendation 1",
    "Concrete actionable recommendation 2",
    "Concrete actionable recommendation 3"
  ],
  "followUps": [
    "Follow-up research question 1",
    "Follow-up research question 2",
    "Follow-up research question 3"
  ]
}
`;

    const prompt = `
RESEARCH QUERY: "${query}"
DEPTH: ${depth}
${projectContext}
Conduct deep research, formulate key analytical pillars, cite authoritative sources, and provide structured insights.
`;

    const aiRes = await generateTextWithFallback({
      prompt,
      system: systemPrompt,
      temperature: 0.2,
      maxOutputTokens: 4000,
    });

    let raw = (aiRes.text || "").trim();
    if (raw.startsWith("```json")) raw = raw.slice(7);
    if (raw.startsWith("```")) raw = raw.slice(3);
    if (raw.endsWith("```")) raw = raw.slice(0, -3);
    raw = raw.trim();

    const parsed = JSON.parse(raw);

    // Build unified markdown report for easy export or saving to Docs
    const sourceLinks = (parsed.sources || [])
      .map(
        (s: ResearchSource, i: number) =>
          `[${i + 1}] [${s.title}](${s.url}) - *${s.domain}*\n> "${s.snippet}"`
      )
      .join("\n\n");

    const sectionsMd = (parsed.sections || [])
      .map(
        (sec: DeepResearchSection) => `
### ${sec.title}
${sec.content}

${sec.keyTakeaway ? `> **Key Takeaway:** ${sec.keyTakeaway}` : ""}
`
      )
      .join("\n");

    const recommendationsMd = (parsed.recommendations || [])
      .map((r: string) => `- ${r}`)
      .join("\n");

    const fullMarkdown = `
# Research Report: ${query}
*Generated by Orbitwork Deep Research Engine*

## Executive Summary
${parsed.summary}

## Deep-Dive Analysis
${sectionsMd}

## Actionable Recommendations
${recommendationsMd}

## Citations & Sources
${sourceLinks}
`.trim();

    const report: DeepResearchReport = {
      query,
      summary: parsed.summary,
      sections: parsed.sections || [],
      sources: parsed.sources || [],
      recommendations: parsed.recommendations || [],
      followUps: parsed.followUps || [],
      markdownReport: fullMarkdown,
    };

    return NextResponse.json({ report });
  } catch (err: any) {
    console.error("[Deep Research Error]:", err);
    return NextResponse.json(
      { error: err.message || "Failed to complete deep research" },
      { status: 500 }
    );
  }
}
